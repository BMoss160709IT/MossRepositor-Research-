            print(f"\n Pre-trained weights saved to: {save_path}")

            if save_metadata:
                metadata = {
                    'seed': seed,
                    'days': days,
                    'n_variations': n_variations,
                    'variations': [building_configs[i] for i in indices],
                    'results': all_results,
                    'avg_energy': np.mean([r['energy'] for r in all_results]) if all_results else 0,
                    'avg_overrides': np.mean([r['override_count'] for r in all_results]) if all_results else 0
                }
