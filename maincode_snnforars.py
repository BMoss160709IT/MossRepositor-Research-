    print(f"\nPre-training completed.")
    if all_results:
        print(f"  Avg energy: {np.mean([r['energy'] for r in all_results]):.1f} kWh")
        print(f"  Avg overrides: {np.mean([r['override_count'] for r in all_results]):.1f}\n")

    return avg_weights

