def remove_outliers_iqr(data, multiplier=1.5, return_info=False):
    data = np.array(data)
    n_total = len(data)

    if n_total < 4:
        if return_info:
            return data, 0, np.ones(n_total, dtype=bool), [], []
        return data, 0, np.ones(n_total, dtype=bool)

    q1 = np.percentile(data, 25)
    q3 = np.percentile(data, 75)
    iqr = q3 - q1

    if iqr == 0:
        if return_info:
            return data, 0, np.ones(n_total, dtype=bool), [], []
        return data, 0, np.ones(n_total, dtype=bool)

    lower_bound = q1 - multiplier * iqr
    upper_bound = q3 + multiplier * iqr

    mask = (data >= lower_bound) & (data <= upper_bound)

    data_clean = data[mask]
    n_removed = n_total - len(data_clean)

    if return_info:
        outlier_indices = np.where(~mask)[0].tolist()
        outlier_values = data[~mask].tolist()
        return data_clean, n_removed, mask, outlier_indices, outlier_values

    return data_clean, n_removed, mask

